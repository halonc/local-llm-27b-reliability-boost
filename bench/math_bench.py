def ans_of(expr, ndigits):
    """标准答案由 Python 算；日期题走专门分支。"""
    e = expr.strip()
    if e.startswith("DATE:"):
        _, a, b = e.split(":")
        d1 = dt.date.fromisoformat(a); d2 = dt.date.fromisoformat(b)
        return abs((d2 - d1).days)
    if e.startswith("DATEADD:"):
        _, a, n = e.split(":")
        d = dt.date.fromisoformat(a) + dt.timedelta(days=int(n))
        return "%s（%s）" % (d.isoformat(), "一二三四五六日"[d.weekday()])
    if e.startswith("WEEKDAY:"):
        _, a, tgt = e.split(":")
        d = dt.date.fromisoformat(a)
        base = d - dt.timedelta(days=d.weekday())
        idx = "一二三四五六日".index("日" if tgt[-1] == "天" else tgt[-1])
        off = {"本周": 0, "这周": 0, "下周": 7, "上周": -7}[tgt[:2]]
        r = base + dt.timedelta(days=off + idx)
        return "%s（%s）" % (r.isoformat(), "一二三四五六日"[r.weekday()])
    v = eval(e, {"__builtins__": {}}, {"D": D})  # 仅本地固定题库，非用户输入
    v = D(str(v))
    if ndigits == 0:
        return int(v.quantize(D("1"), rounding=ROUND_HALF_UP))
    return format(v.quantize(D(1).scaleb(-ndigits), rounding=ROUND_HALF_UP), ".%df" % ndigits)


PROMPT_HEAD = ("请计算下面的问题。**只输出一行**，格式严格为：答案=<数值><单位>\n"
               "不要写步骤、不要解释、不要加粗。\n\n")


def num(s):
    m = re.findall(r"-?\d[\d,]*\.?\d*", s.replace(",", ""))
    return [D(x) for x in m] if m else []


def run(args):
    rows = []
    t0 = time.time()
    for i, (cat, prompt, expr, nd, unit) in enumerate(BANK):
        std = ans_of(expr, nd)
        body = json.dumps({"model": args.model, "messages": [{"role": "user", "content": PROMPT_HEAD + prompt}],
                           "max_tokens": 120, "temperature": 0, "stream": False,
                           "chat_template_kwargs": {"enable_thinking": False}}).encode()
        req = urllib.request.Request(args.endpoint.rstrip("/") + "/chat/completions", data=body,
                                     headers={"Content-Type": "application/json"})
        tt = time.time()
        try:
            d = json.loads(urllib.request.urlopen(req, timeout=300).read())
            out = (d["choices"][0]["message"].get("content") or "").strip()
        except Exception as e:
            out = "ERROR %s" % e
        dur = time.time() - tt
        # 判分：优先取「答案=」后的数字；日期题比字符串
        cand = re.search(r"答案\s*[=:：]\s*(.+)", out)
        seg = cand.group(1) if cand else out
        ok = False
        if isinstance(std, int) or isinstance(std, str) and not std.replace(".", "").isdigit():
            if isinstance(std, int):
                ns = num(seg)
                ok = any(abs(x - D(std)) <= D("0.6") for x in ns)
            else:
                m = re.search(r"(\d{4}-\d{2}-\d{2})", std)
                ok = bool(m and m.group(1) in out)
        else:
            ns = num(seg)
            ok = bool(ns) and abs(ns[0] - D(str(std))) <= max(D("0.006"), abs(D(str(std))) * D("0.002"))
        rows.append(dict(i=i, cat=cat, prompt=prompt, std=str(std), out=out, ok=ok, dur=dur))

    # 统计
    per = {}
    for r in rows:
        p = per.setdefault(r["cat"], [0, 0])
        p[1] += 1; p[0] += 1 if r["ok"] else 0
    print("\n== 按类别 ==")
    for k, (a, b) in per.items():
        flag = "心算OK" if a == b else ("必须走Python" if a <= 3 else "建议走Python")
        print("  %-10s %2d/%2d  %s" % (k, a, b, flag))
    total_ok = sum(1 for r in rows if r["ok"])
    print("\n  合计 %d/%d（%.1f%%），用时 %.1f min" % (total_ok, len(rows), 100.0 * total_ok / len(rows), (time.time() - t0) / 60))
    print("\n== 错题 ==")
    for r in rows:
        if not r["ok"]:
            print("  [%s] %s\n    标准=%s 模型=%s" % (r["cat"], r["prompt"][:40], r["std"], r["out"][:60].replace("\n", " ")))
    json.dump(dict(tag=args.tag, model=args.model, per=per, rows=rows),
              open(os.path.join(HERE, "math-%s.json" % args.tag), "w"), ensure_ascii=False, indent=2)
    print("\n明细: tools/model-ab/math-%s.json" % args.tag)


def show():
    for i, (cat, prompt, expr, nd, unit) in enumerate(BANK):
        print("%3d [%-10s] %-46s -> %s %s" % (i, cat, prompt[:46], ans_of(expr, nd), unit))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("action", choices=["bank", "run"])
    ap.add_argument("--endpoint", default="http://127.0.0.1:8080/v1")
    ap.add_argument("--model", default="R9700-Qwen3.8-27B-W3A4-HIP")
    ap.add_argument("--tag", default="paiton")
    a = ap.parse_args()
    show() if a.action == "bank" else run(a)


if __name__ == "__main__":
    main()
